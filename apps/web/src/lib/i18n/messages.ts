export function t(locale: LocaleCode, key: MessageKey): string {
  if (locale === "en") return en[key];
  const pack = packs[locale];
  return pack?.[key] ?? (locale === "en-plain" ? enPlain[key] : undefined) ?? en[key];
}

export function getMessages(locale: LocaleCode): Record<MessageKey, string> {
  const out = { ...en };
  const pack = packs[locale];
  if (pack) {
    for (const [k, v] of Object.entries(pack)) {
      if (v) out[k as MessageKey] = v;
    }
  }
  return out;
}

